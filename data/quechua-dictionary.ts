// Diccionario inverso: Quechua → Español
export const quEsDictionary: Record<string, string> = {};
Object.entries(esQuDictionary).forEach(([es, qu]) => {
  const quLower = qu.toLowerCase();
  if (!quEsDictionary[quLower]) {
    quEsDictionary[quLower] = es;
  }
});

// ── Función de traducción por diccionario ──
export function translateWithDictionary(
  text: string,
  direction: "es-qu" | "qu-es"
): string {
  const dict = direction === "es-qu" ? esQuDictionary : quEsDictionary;

  // Ordenar entradas por longitud descendente (frases largas primero)
  const sortedEntries = Object.entries(dict).sort(
    (a, b) => b[0].length - a[0].length
  );

  const usedRanges: { start: number; end: number }[] = [];

  const lowerText = text.toLowerCase();

  for (const [source] of sortedEntries) {
    const escaped = source.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    // Usar boundary flexible para soportar caracteres especiales del quechua
    const regex = new RegExp(`(?:^|[\\s,.!?;:])${escaped}(?=$|[\\s,.!?;:])`, "gi");
    let match;

    while ((match = regex.exec(lowerText)) !== null) {
      // Ajustar inicio si el match incluye un separador al principio
      let matchStart = match.index;
      let matchedText = match[0];
      if (/[\s,.!?;:]/.test(matchedText[0])) {
        matchStart += 1;
        matchedText = matchedText.substring(1);
      }
      const matchEnd = matchStart + matchedText.length;

      // Verificar que no se superpone con reemplazos existentes
      const overlaps = usedRanges.some(
        (r) => matchStart < r.end && matchEnd > r.start
      );

      if (!overlaps) {
        usedRanges.push({ start: matchStart, end: matchEnd });
      }
    }
  }

  // Construir resultado con reemplazos
  if (usedRanges.length === 0) return text;

  // Ordenar rangos por posición
  usedRanges.sort((a, b) => a.start - b.start);

  let finalResult = "";
  let lastEnd = 0;

  for (const range of usedRanges) {
    // Añadir texto no modificado antes del match
    finalResult += text.substring(lastEnd, range.start);

    // Obtener la palabra original y buscar su traducción
    const originalWord = text.substring(range.start, range.end);
    const translation = dict[originalWord.toLowerCase()];

    if (translation) {
      // Preservar capitalización
      if (originalWord[0] === originalWord[0].toUpperCase()) {
        finalResult += translation.charAt(0).toUpperCase() + translation.slice(1);
      } else {
        finalResult += translation;
      }
    } else {
      finalResult += originalWord;
    }

    lastEnd = range.end;
  }

  // Añadir el resto del texto
  finalResult += text.substring(lastEnd);

  return finalResult;
}
